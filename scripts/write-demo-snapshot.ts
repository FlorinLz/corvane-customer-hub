import "dotenv/config";

import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

// Regenerates data/demo-snapshot.js: runs the seed at the default demo clock (cache-only GLEIF) on the database that
// DATABASE_ADMIN_URL points at, then reads every table back. Local Docker only: it TRUNCATES that database.
// Run it whenever tests/unit/demo-snapshot.test.ts says the snapshot is stale: `npm run demo:snapshot`.
async function main() {
  // The clock and cache source must be set before any module reads them, hence the dynamic imports below.
  const { SNAPSHOT_CLOCK_START } = await import("./demo-snapshot-lib");
  process.env.DEMO_CLOCK_START = SNAPSHOT_CLOCK_START;
  delete process.env.DEMO_CLOCK_ANCHOR;
  process.env.GLEIF_SEED_SOURCE = "cache";
  delete process.env.GLEIF_CACHE_PATH;

  const url = process.env.DATABASE_ADMIN_URL ?? "";
  if (!/@(localhost|127\.0\.0\.1)[:/]/.test(url)) throw new Error("demo:snapshot truncates the database; DATABASE_ADMIN_URL must point at localhost.");

  const { createAdminDb } = await import("../src/server/db-admin");
  const { resetDemoData } = await import("../src/server/demo-reset");
  const { today } = await import("../src/lib/dates");
  const { dumpSnapshot } = await import("./demo-snapshot-lib");

  const db = createAdminDb();
  try {
    await resetDemoData(db);
    const snapshot = await dumpSnapshot(db, today());
    const path = resolve(__dirname, "../data/demo-snapshot.js");
    writeFileSync(path, `// Generated by \`npm run demo:snapshot\`. Do not edit.\nexport default JSON.parse(${JSON.stringify(JSON.stringify(snapshot))});\n`);
    const rows = snapshot.tables.reduce((n, t) => n + t.rows.length, 0);
    console.log(`Wrote data/demo-snapshot.js: ${snapshot.tables.length} tables, ${rows} rows, seed day ${snapshot.seedToday}.`);
  } finally {
    await db.$disconnect();
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
