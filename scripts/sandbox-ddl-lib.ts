import { createHash } from "node:crypto";
import { readdirSync, readFileSync } from "node:fs";
import { join, resolve } from "node:path";

const ROOT = resolve(__dirname, "..");

/** A migration whose first line is this belongs to the public schema only (the sandbox registry) and is left out of the DDL. */
export const SANDBOX_SKIP_MARKER = "-- sandbox:skip";

/**
 * Statements that must stay global. They are removed from the DDL a sandbox runs: the extension lives in public once and every sandbox reaches its
 * operator classes through the search_path (`<sandbox>, public`).
 */
const GLOBAL_STATEMENT = /^\s*CREATE\s+(EXTENSION|SCHEMA)\b[^;]*;[ \t]*$/gim;

export interface SandboxDdl {
  /** Every migration in order, minus the registry migrations and minus the global statements. */
  sql: string;
  /** prisma/grants.sql, which a sandbox gets rewritten for its own schema (grantsForSandbox in src/lib/sandbox.ts). */
  grants: string;
  /** sha256 of `sql` and `grants`: a change to either makes every existing sandbox out of date. */
  hash: string;
  /** The migrations that went in, in order. */
  migrations: string[];
}

export function stripGlobalStatements(sql: string): string {
  return sql.replace(GLOBAL_STATEMENT, "-- (left out of the sandbox DDL: global statement)");
}

export function buildSandboxDdl(migrationsDir: string = join(ROOT, "prisma", "migrations")): SandboxDdl {
  const names = readdirSync(migrationsDir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();
  const included: string[] = [];
  const parts: string[] = [];
  for (const name of names) {
    const sql = readFileSync(join(migrationsDir, name, "migration.sql"), "utf-8");
    if (sql.trimStart().startsWith(SANDBOX_SKIP_MARKER)) continue;
    included.push(name);
    parts.push(`-- Migration ${name}\n${stripGlobalStatements(sql).trim()}\n`);
  }
  const sql = parts.join("\n");
  const grants = readFileSync(join(migrationsDir, "..", "grants.sql"), "utf-8");
  return { sql, grants, hash: createHash("sha256").update(sql).update("\n--grants--\n").update(grants).digest("hex"), migrations: included };
}

/** The text of data/sandbox-ddl.sql: a header with the hash, then the DDL. */
export function sandboxDdlFile(ddl: SandboxDdl): string {
  return `-- GENERATED by scripts/write-sandbox-ddl.ts (npm run sandbox:ddl) from prisma/migrations. Do not edit.
-- Run with search_path set to "<sandbox>, public" (src/server/sandbox.ts). Migrations: ${ddl.migrations.join(", ")}
-- ddlHash: ${ddl.hash}

${ddl.sql}
-- ===== prisma/grants.sql (rewritten for the sandbox's own schema when it is made) =====
${ddl.grants.split("\n").map((l) => `-- ${l}`).join("\n")}
`;
}

/** The module the app imports (a plain .js file, like data/demo-snapshot.js, so no file read at runtime). */
export function sandboxDdlModule(ddl: SandboxDdl): string {
  return `// Generated by \`npm run sandbox:ddl\`. Do not edit. The same DDL as data/sandbox-ddl.sql.\nexport default ${JSON.stringify({ ddlHash: ddl.hash, sql: ddl.sql, grants: ddl.grants })};\n`;
}
