import { createHash } from "node:crypto";
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * The text of scripts/neon-rebuild.sql: the one file to run by hand on a hosted Postgres (Neon) to rebuild the database from the baseline.
 * It embeds the baseline migration, the Prisma history row for it (so `prisma migrate status`, which the Vercel production build runs, finds
 * nothing pending) and the grants of prisma/grants.sql. Generated, never edited by hand: `npm run neon:rebuild-sql` rewrites the file, and
 * tests/unit/neon-rebuild.test.ts fails when the file and its sources differ.
 */
export function buildNeonRebuildSql(root = process.cwd()): string {
  const migrationsDir = join(root, "prisma", "migrations");
  const names = readdirSync(migrationsDir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name);
  if (names.length !== 1) throw new Error(`Expected exactly one baseline migration, found: ${names.join(", ") || "none"}`);
  const name = names[0];
  const baseline = readFileSync(join(migrationsDir, name, "migration.sql"), "utf-8");
  // Prisma's own checksum: SHA-256 of the migration file.
  const checksum = createHash("sha256").update(baseline).digest("hex");
  const grants = readFileSync(join(root, "prisma", "grants.sql"), "utf-8").trim();

  return `-- Rebuild the database from the baseline migration. RUN BY HAND, on the database you mean to rebuild.
--
-- DESTRUCTIVE: drops the whole "public" schema (every table, row, type, function and extension in it) and recreates it.
-- Nothing is kept. Take a backup first if anything in the database matters.
--
-- Run it as the ADMIN role (the one the app's DATABASE_ADMIN_URL uses: it must be allowed to drop and create the public schema, and it
-- becomes the owner of everything created here). The runtime role hub_app must already exist; this file creates no roles and holds no
-- password or connection string. With psql, from a shell where the connection string is in $DATABASE_ADMIN_URL:
--
--     psql "$DATABASE_ADMIN_URL" -v ON_ERROR_STOP=1 -f scripts/neon-rebuild.sql
--
-- Everything runs in one transaction: if any statement fails, nothing is changed.
-- After it: load the demo data with the app's seed (npm run db:seed with DATABASE_ADMIN_URL pointing at this database), then check
-- \`npx prisma migrate status\` reports "Database schema is up to date".
--
-- GENERATED by scripts/neon-rebuild-sql.ts (npm run neon:rebuild-sql) from prisma/migrations/${name}/migration.sql and prisma/grants.sql.
-- Do not edit by hand.

BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'hub_app') THEN
    RAISE EXCEPTION 'The role hub_app does not exist. Create it first (docker/initdb/01-roles.sql shows the statement; choose your own password).';
  END IF;
END
$$;

-- 1. A fresh public schema, owned by the role running this file; hub_app may use it.
DROP SCHEMA IF EXISTS public CASCADE;
CREATE SCHEMA public;
GRANT USAGE ON SCHEMA public TO hub_app;

-- 2. The baseline migration: ${name}
${baseline.trim()}

-- 3. Prisma's migration history: the baseline is recorded as applied, so \`prisma migrate status\` finds nothing pending.
CREATE TABLE "_prisma_migrations" (
    "id" VARCHAR(36) NOT NULL,
    "checksum" VARCHAR(64) NOT NULL,
    "finished_at" TIMESTAMPTZ,
    "migration_name" VARCHAR(255) NOT NULL,
    "logs" TEXT,
    "rolled_back_at" TIMESTAMPTZ,
    "started_at" TIMESTAMPTZ NOT NULL DEFAULT now(),
    "applied_steps_count" INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT "_prisma_migrations_pkey" PRIMARY KEY ("id")
);
INSERT INTO "_prisma_migrations" ("id", "checksum", "finished_at", "migration_name", "applied_steps_count")
VALUES ('00000000-0000-4000-8000-000000000001', '${checksum}', now(), '${name}', 1);

-- 4. The runtime role's grants (prisma/grants.sql, unchanged).
${grants}

-- 5. hub_app only reads the migration history (the production build runs \`prisma migrate status\` as hub_app).
REVOKE INSERT, UPDATE ON "_prisma_migrations" FROM hub_app;

COMMIT;
`;
}
